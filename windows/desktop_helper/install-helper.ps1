# GrokPC Windows desktop helper — NO administrator rights needed.
# Installs a per-user Python venv and a logon scheduled task that starts the
# helper in your interactive session so it can drive CapCut and read idle time.
#
#   Set-ExecutionPolicy -Scope Process Bypass
#   .\windows\desktop_helper\install-helper.ps1
#
# Prerequisites: Python 3.10+ for the current user (not admin).
# If Python is missing, this script offers:  winget install Python.Python.3.12 --scope user
$ErrorActionPreference = "Stop"
$TaskName = "GrokPC Desktop Helper"
$StateDir = Join-Path $env:LOCALAPPDATA "GrokPC"
$VenvDir = Join-Path $StateDir "helper-venv"
$EnvFile = Join-Path $StateDir "helper.env"
$LogFile = Join-Path $StateDir "helper.log"
$Distro = "Ubuntu-24.04"

New-Item -ItemType Directory -Force -Path $StateDir | Out-Null

function Write-Log {
    param([string]$Message, [string]$Color = "Gray")
    $line = "[{0}] {1}" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"), $Message
    Add-Content -Path $LogFile -Value $line
    Write-Host $Message -ForegroundColor $Color
}

function Get-HelperSrc {
    if (-not $PSScriptRoot) { throw "Is script ko file se chalao." }
    $src = Join-Path $PSScriptRoot "helper.py"
    if (-not (Test-Path $src)) { throw "helper.py nahi mila: $src" }
    return (Resolve-Path $PSScriptRoot).Path
}

function Get-Python {
    foreach ($cmd in @("py", "python", "python3")) {
        $exe = Get-Command $cmd -ErrorAction SilentlyContinue
        if (-not $exe) { continue }
        try {
            $ver = & $exe.Source --version 2>&1 | Out-String
            if ($ver -match "Python 3\.(\d+)") {
                $minor = [int]$Matches[1]
                if ($minor -ge 10) { return $exe.Source }
            }
        } catch {}
        # `py -3` launcher
        if ($cmd -eq "py") {
            try {
                $ver = & $exe.Source -3 --version 2>&1 | Out-String
                if ($ver -match "Python 3\.") { return $exe.Source }
            } catch {}
        }
    }
    return $null
}

function Get-AgentToken {
    # Pull AGENT_TOKEN from the WSL .env without printing it.
    try {
        $old = [Console]::OutputEncoding
        [Console]::OutputEncoding = New-Object System.Text.UnicodeEncoding $false, $false
        $names = @(wsl.exe -l -q 2>$null | ForEach-Object { ($_ -replace "`0", "").Trim() } | Where-Object { $_ })
        [Console]::OutputEncoding = $old
    } catch { $names = @() }
    if ($names -notcontains $Distro) { return "" }
    $line = & wsl.exe -d $Distro -u root -- bash -lc "grep -E '^AGENT_TOKEN=' /app/agent/.env 2>/dev/null | tail -n 1" | Out-String
    $line = ($line -replace "`0", "").Trim()
    if ($line -match '^AGENT_TOKEN=(.*)$') {
        return $Matches[1].Trim().Trim('"').Trim("'")
    }
    return ""
}

function Write-HelperEnv {
    param([string]$Token)
    $content = @(
        "# Generated by install-helper.ps1. Do not commit."
        "GROKPC_HELPER_TOKEN=$Token"
        "GROKPC_HELPER_HOST=127.0.0.1"
        "GROKPC_HELPER_PORT=8765"
    )
    $content | Set-Content -Path $EnvFile -Encoding ASCII
    try { icacls $EnvFile /inheritance:r /grant:r "${env:USERNAME}:(R,W)" | Out-Null } catch {}
}

$SrcDir = Get-HelperSrc
Write-Host ""
Write-Host "=== GrokPC Desktop Helper (no admin) ===" -ForegroundColor Green
Write-Host "Source: $SrcDir"
Write-Host "Install dir: $StateDir"
Write-Host ""

# Copy helper files so the helper keeps working if the repo ZIP is deleted.
$InstallSrc = Join-Path $StateDir "desktop_helper"
New-Item -ItemType Directory -Force -Path $InstallSrc | Out-Null
Copy-Item -Force (Join-Path $SrcDir "helper.py") (Join-Path $InstallSrc "helper.py")
Copy-Item -Force (Join-Path $SrcDir "requirements.txt") (Join-Path $InstallSrc "requirements.txt")
$Starter = Join-Path $StateDir "start-helper.ps1"
Copy-Item -Force (Join-Path $SrcDir "start-helper.ps1") $Starter

$py = Get-Python
if (-not $py) {
    Write-Log "Python 3.10+ nahi mila." "Yellow"
    Write-Log "User-scope install (admin nahi chahiye):" "Yellow"
    Write-Log "  winget install Python.Python.3.12 --scope user" "Cyan"
    Write-Log "Phir is script ko dobara chalao. Microsoft Store wala Python bhi chalega." "Yellow"
    $winget = Get-Command winget -ErrorAction SilentlyContinue
    if ($winget) {
        Write-Host "Abhi winget se Python install karun? (y/N) " -NoNewline -ForegroundColor Yellow
        $ans = Read-Host
        if ($ans -match '^[yY]') {
            & winget install Python.Python.3.12 --scope user --accept-package-agreements --accept-source-agreements
            $env:Path = [Environment]::GetEnvironmentVariable("Path", "User") + ";" + [Environment]::GetEnvironmentVariable("Path", "Machine")
            $py = Get-Python
        }
    }
    if (-not $py) { throw "Python ke bina helper install nahi ho sakta." }
}
Write-Log "Python: $py" "Green"

# py launcher wants -3
$pyArgs = @()
if ((Split-Path $py -Leaf) -eq "py.exe" -or (Split-Path $py -Leaf) -eq "py") { $pyArgs = @("-3") }

if (-not (Test-Path (Join-Path $VenvDir "Scripts\python.exe"))) {
    Write-Log "Creating venv at $VenvDir"
    & $py @pyArgs -m venv $VenvDir
}
$venvPy = Join-Path $VenvDir "Scripts\python.exe"
& $venvPy -m pip install --upgrade pip
& $venvPy -m pip install -r (Join-Path $InstallSrc "requirements.txt")
Write-Log "Python packages installed." "Green"

$token = Get-AgentToken
if (-not $token) {
    if (Test-Path $EnvFile) {
        Write-Log "WSL se token nahi mila; existing helper.env rakh raha hoon." "Yellow"
    } else {
        Write-Log "AGENT_TOKEN WSL me nahi mila. helper.env me TOKEN=change-me likh do, same as /app/agent/.env" "Yellow"
        Write-HelperEnv -Token "change-me"
    }
} else {
    Write-HelperEnv -Token $token
    Write-Log "Token WSL se helper.env me copy ho gaya (print nahi kiya)." "Green"
}

# Per-user scheduled task, Limited run level — no admin.
$arg = "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$Starter`""
$action = New-ScheduledTaskAction -Execute "powershell.exe" -Argument $arg
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
Write-Log "Scheduled task '$TaskName' (at logon, no admin)." "Green"

# Start now
Write-Log "Helper ab start kar raha hoon..."
Start-Process -FilePath "powershell.exe" -ArgumentList "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$Starter`"" -WindowStyle Hidden
Start-Sleep -Seconds 2
Write-Log ""
Write-Log "Helper 127.0.0.1:8765 pe chalna chahiye. WSL agent WINDOWS_HELPER_URL=http://127.0.0.1:8765 use karega." "Green"
Write-Log "CapCut Windows pe install karo (free). Media Videos\GrokPC\import me jayega." "Cyan"
Write-Log "Stop:  Stop-ScheduledTask -TaskName '$TaskName'  aur helper process band karo." "Gray"
Write-Log "Log: $LogFile"
